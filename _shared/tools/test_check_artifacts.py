"""Tests for check_artifacts.py -- the "measured something" half of the artifact gate, and the
pre-commit manifest.

Run: python test_check_artifacts.py   (exit 0 = all passed)
"""
import contextlib
import io
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_artifacts import _drop_excluded, main, scope_of  # noqa: E402


def scope(text: str):
    with tempfile.TemporaryDirectory() as d:
        p = Path(d) / "code-quality-review.md"
        p.write_text(text, encoding="utf-8")
        return scope_of(p)


class DropExcludedTests(unittest.TestCase):
    def test_line_without_keyword_is_kept(self):
        self.assertEqual(_drop_excluded("77 files, 6225 lines"), "77 files, 6225 lines")

    def test_parenthesised_note_goes_scope_stays(self):
        kept = _drop_excluded("77 files, 6225 lines (of these, 5267 are a generated designer file)")
        self.assertIn("77 files", kept)
        self.assertNotIn("5267", kept)

    def test_clause_with_keyword_goes_other_clause_stays(self):
        kept = _drop_excluded("Scope: 12 files reviewed; 3 files generated, skipped")
        self.assertIn("12 files", kept)
        self.assertNotIn("3 files", kept)

    def test_single_clause_with_keyword_drops_the_line(self):
        self.assertEqual(_drop_excluded("4000 lines of generated code"), "")


class ScopeOfTests(unittest.TestCase):
    def test_scope_line_carrying_its_own_generated_note_is_measured(self):
        # PROJ-11212: the old rule dropped this whole line and called a real review HOLLOW.
        ok, evidence = scope("# Review\n\nDiff reviewed: 77 files, +6225/-581 lines "
                             "(of these, +5267 is a generated migration designer, skimmed only)\n")
        self.assertTrue(ok, evidence)
        self.assertIn("77", evidence)
        self.assertNotIn("5267", evidence)

    def test_only_generated_figures_is_still_hollow(self):
        ok, evidence = scope("# Review\n\n12000 lines generated by the scaffolder, not reviewed\n")
        self.assertFalse(ok, evidence)

    def test_all_zero_scope_is_still_hollow(self):
        ok, _ = scope("# Review\n\nScope: 0 files, 0 added lines reviewed\n")
        self.assertFalse(ok)

    def test_last_scope_section_wins(self):
        # A second pass appended at the bottom must be the one that is read.
        ok, evidence = scope("# Review\n\n## Scope\n2 repos, 384 lines\n\n## Notes\nx\n\n"
                             "## Scope (pass 2)\n0 files, 0 lines\n")
        self.assertFalse(ok, evidence)


class PreCommitGateTests(unittest.TestCase):
    """PROJ-10837: pre-commit checked 2 files while verify.md demanded 5. Each test is one
    file the prose calls mandatory; the gate must refuse when it is missing or hollow."""

    FULL = {
        "code-quality-review.md": "# Review\n\nScope: 66 files, 945 added lines reviewed\n",
        "plan.md": "# Plan\n\nsomething\n",
        "run-telemetry.yaml": "ticket_id: X\nticket_type: crud-feature\nphases:\n  - {phase: plan}\n",
        "implement-summary.md": "# Summary\n\nRegression: 1435 passed, 0 failed, 0 skipped (baseline 1432)\n",
        "test-evidence/TC-1/02_response.txt": "Expected: 429\nObserved: 429\n",
        "ticket-context.yaml": "armed_gates: [G1]\n",
        "legacy-contract.md": "# Contract\n",
    }

    def run_gate(self, files, ticket_type="crud-feature", drop=(), gate="pre-commit"):
        with tempfile.TemporaryDirectory() as d:
            for rel, text in files.items():
                if rel in drop:
                    continue
                p = Path(d) / rel
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(text, encoding="utf-8")
            out = io.StringIO()
            argv = sys.argv
            sys.argv = ["check_artifacts.py", d, gate, "--type", ticket_type]
            try:
                with contextlib.redirect_stdout(out), contextlib.redirect_stderr(out):
                    code = main()
            finally:
                sys.argv = argv
            return code, out.getvalue()

    def test_full_set_passes(self):
        code, out = self.run_gate(self.FULL)
        self.assertEqual(code, 0, out)

    def test_failure_mode_without_id_key_is_hollow(self):
        files = dict(self.FULL, **{"run-telemetry.yaml": "ticket_type: crud-feature\nphases:\n  - {phase: plan}\n"
                                   "failure_modes_hit:\n  - {fm: FM-DLL-LOCKED, where: tests}\n"})
        code, out = self.run_gate(files)
        self.assertEqual(code, 2, out)
        self.assertIn("without `id: FM-...`", out)
        ok = dict(self.FULL, **{"run-telemetry.yaml": "ticket_type: crud-feature\nphases:\n  - {phase: plan}\n"
                                "failure_modes_hit:\n  - {id: FM-DLL-LOCKED, where: tests}\n"})
        self.assertEqual(self.run_gate(ok)[0], 0)

    def test_missing_telemetry_blocks(self):
        code, out = self.run_gate(self.FULL, drop=("run-telemetry.yaml",))
        self.assertEqual(code, 2, out)

    def test_empty_telemetry_is_hollow(self):
        files = dict(self.FULL, **{"run-telemetry.yaml": "ticket_id: X\nphases: []\n"})
        code, out = self.run_gate(files)
        self.assertEqual(code, 2, out)
        self.assertIn("HOLLOW", out)

    def test_summary_without_regression_line_is_hollow(self):
        files = dict(self.FULL, **{"implement-summary.md": "# Summary\n\nRegression check: PASS\n"})
        code, out = self.run_gate(files)
        self.assertEqual(code, 2, out)
        self.assertIn("implement-summary.md", out)

    def test_regression_with_failures_or_zero_tests_is_hollow(self):
        for line in ("Regression: 10 passed, 2 failed, 0 skipped", "Regression: 0 passed, 0 failed, 0 skipped"):
            files = dict(self.FULL, **{"implement-summary.md": f"# S\n\n{line}\n"})
            code, out = self.run_gate(files)
            self.assertEqual(code, 2, f"{line}\n{out}")

    def test_missing_test_evidence_blocks_crud_feature(self):
        code, out = self.run_gate(self.FULL, drop=("test-evidence/TC-1/02_response.txt",))
        self.assertEqual(code, 2, out)

    def test_test_evidence_waived_for_refactor(self):
        code, out = self.run_gate(self.FULL, ticket_type="refactor", drop=("test-evidence/TC-1/02_response.txt",))
        self.assertEqual(code, 0, out)

    def test_api_test_skipped_in_telemetry_waives_evidence(self):
        files = dict(self.FULL, **{"run-telemetry.yaml": "ticket_type: crud-feature\nphases:\n  - {phase: plan}\n"
                                   "skipped_phases:\n  - {phase: api-test, reason: deploy first}\n"})
        code, out = self.run_gate(files, drop=("test-evidence/TC-1/02_response.txt",))
        self.assertEqual(code, 0, out)

    def test_armed_gates_need_legacy_contract(self):
        code, out = self.run_gate(self.FULL, drop=("legacy-contract.md",))
        self.assertEqual(code, 2, out)
        self.assertIn("legacy-contract.md", out)

    def test_no_armed_gates_no_contract_needed(self):
        files = dict(self.FULL, **{"ticket-context.yaml": "armed_gates: []\n"})
        code, out = self.run_gate(files, drop=("legacy-contract.md",))
        self.assertEqual(code, 0, out)

    def test_done_gate_needs_telemetry_and_summary(self):
        code, out = self.run_gate(self.FULL, gate="done")
        self.assertEqual(code, 0, out)
        code, out = self.run_gate(self.FULL, gate="done", drop=("implement-summary.md",))
        self.assertEqual(code, 2, out)


if __name__ == "__main__":
    unittest.main(verbosity=1)
